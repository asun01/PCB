    public static bool AllSucceeded(
        IReadOnlyList<BulkChainOutcome> outcomes)
    {
        ArgumentNullException.ThrowIfNull(outcomes);

        return outcomes.Count == 500 &&
               outcomes.Select(x => x.Id)
                   .OrderBy(x => x)
                   .SequenceEqual(Enumerable.Range(1, 500)) &&
               outcomes.All(x =>
                   x.Success &&
                   double.IsFinite(x.Metric) &&
                   float.IsFinite(x.Point.X) &&
                   float.IsFinite(x.Point.Y) &&
                   float.IsFinite(x.Bounds.X) &&
                   float.IsFinite(x.Bounds.Y) &&
                   float.IsFinite(x.Bounds.Width) &&
                   float.IsFinite(x.Bounds.Height));
    }
